    /**
     * Display the specified resource.
     *
     * @param  string  $id
     * @return \Illuminate\Http\Response
     */
    public function show($id)
    {
        $mahasiswa = Mahasiswa::with('pesertas.tim.kategori')->findOrFail($id);
        return view('admin.pages.show_peserta', compact('mahasiswa'));
    }

    /**
     * Show the form for editing the specified resource.
     *
     * @param  string  $id
     * @return \Illuminate\Http\Response
     */
    public function edit($id)
    {
        $mahasiswa = Mahasiswa::findOrFail($id);
        return view('admin.pages.edit_peserta', compact('mahasiswa'));
    }

    /**
     * Update the specified resource in storage.
     *
     * @param  \Illuminate\Http\Request  $request
     * @param  string  $id
     * @return \Illuminate\Http\Response
     */
    public function update(Request $request, $id)
    {
        $request->validate([
            'nama' => 'required',
            'email' => 'required|email',
            'no_hp' => 'required',
        ]);

        Mahasiswa::updateMahasiswa($id, $request->nama, $request->email, $request->no_hp);
        return redirect()->route('admin.peserta.index')->with('success', 'Data peserta berhasil diubah');
    }

